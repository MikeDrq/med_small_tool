"""Dataset for Module 2 and Module 3 ROI sequence classifiers."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Callable

import torch
from torch.utils.data import Dataset


STATUS_TO_ID = {"normal": 0, "degeneration": 1, "tear": 2}
SIDE_TO_ID = {"medial": 0, "lateral": 1}


def _read_roi_index(index_or_dir: str | Path) -> list[dict[str, Any]]:
    path = Path(index_or_dir)
    if path.is_dir():
        return [{"roi_path": str(item)} for item in sorted(path.glob("*.pt"))]
    if path.suffix.lower() == ".jsonl":
        records = []
        with path.open("r", encoding="utf-8") as handle:
            for line in handle:
                if line.strip():
                    records.append(json.loads(line))
        return records
    if path.suffix.lower() == ".json":
        data = json.loads(path.read_text(encoding="utf-8"))
        return data["rois"] if isinstance(data, dict) and "rois" in data else data
    raise ValueError(f"Unsupported ROI index: {path}. Use a directory, .jsonl, or .json file.")


class ROIClassificationDataset(Dataset):
    """Loads cached meniscus ROI sequences generated by ``scripts/generate_rois.py``.

    Args:
        index_or_dir: ROI directory, JSONL index, or JSON index. Directory mode
            reads all ``*.pt`` files.
        task: ``"module2"`` for normal/degeneration/tear or ``"module3"`` for
            bucket-handle yes/no.
        sides: Meniscus sides to expose as separate samples.
        module3_tear_only: Restrict Module 3 to menisci whose ground-truth
            Module 2 status is tear.  This matches the paper's conditional
            pipeline and prevents the bucket-handle model from learning the
            much easier normal-versus-tear shortcut.
        transform: Optional sample transform.

    Returns:
        ``sagittal_roi``: FloatTensor ``[1,T,H,W]``.
        ``coronal_roi``: FloatTensor ``[1,T,H,W]``.
        ``side``: ``"medial"`` or ``"lateral"``.
        ``module2_label``: LongTensor scalar.
        ``module3_label``: LongTensor scalar.
        ``label``: Task-selected LongTensor scalar.
    """

    def __init__(
        self,
        index_or_dir: str | Path,
        task: str = "module2",
        sides: tuple[str, ...] = ("medial", "lateral"),
        module3_tear_only: bool = True,
        transform: Callable[[dict[str, Any]], dict[str, Any]] | None = None,
    ):
        if task not in {"module2", "module3"}:
            raise ValueError("task must be 'module2' or 'module3'")
        self.index_or_dir = Path(index_or_dir)
        self.task = task
        self.sides = sides
        self.module3_tear_only = bool(module3_tear_only)
        self.transform = transform
        roi_records = _read_roi_index(index_or_dir)
        self.records: list[dict[str, Any]] = []
        for roi_record in roi_records:
            labels = roi_record.get("labels")
            if task == "module3" and self.module3_tear_only and not isinstance(labels, dict):
                payload = torch.load(roi_record["roi_path"], map_location="cpu", weights_only=True)
                labels = payload["labels"]
            for side in sides:
                if task == "module3" and self.module3_tear_only:
                    if int(labels[f"{side}_status"]) != STATUS_TO_ID["tear"]:
                        continue
                record = {"roi_path": roi_record["roi_path"], "side": side}
                if roi_record.get("group_id") is not None:
                    record["group_id"] = str(roi_record["group_id"])
                if isinstance(labels, dict):
                    record["module2_label"] = int(labels[f"{side}_status"])
                    record["module3_label"] = int(labels[f"{side}_bucket_handle"])
                self.records.append(record)

    def __len__(self) -> int:
        return len(self.records)

    def __getitem__(self, index: int) -> dict[str, Any]:
        record = self.records[index]
        payload = torch.load(record["roi_path"], map_location="cpu", weights_only=True)
        side = record["side"]
        side_payload = payload[side]
        module2_label = int(payload["labels"][f"{side}_status"])
        module3_label = int(payload["labels"][f"{side}_bucket_handle"])
        sample: dict[str, Any] = {
            "case_id": payload["case_id"],
            "group_id": str(payload.get("group_id", record.get("group_id", payload["case_id"]))),
            "side": side,
            "side_id": SIDE_TO_ID[side],
            "sagittal_roi": side_payload["sagittal_roi"].float(),
            "coronal_roi": side_payload["coronal_roi"].float(),
            "boxes": side_payload.get("boxes", {}),
            "module2_label": torch.tensor(module2_label, dtype=torch.long),
            "module3_label": torch.tensor(module3_label, dtype=torch.long),
            "label": torch.tensor(module2_label if self.task == "module2" else module3_label, dtype=torch.long),
            "roi_path": record["roi_path"],
        }
        if self.transform is not None:
            sample = self.transform(sample)
        return sample
